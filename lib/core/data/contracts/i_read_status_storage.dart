// lib/core/data/contracts/i_read_status_storage.dart
//
// قرارداد ذخیره‌سازی برای وضعیت «خوانده‌شده/خوانده‌نشده» هر شعر.
//
// عملیات این اینترفیس دقیقاً همان سه کاری است که در کد فعلی (پخش‌شده در
// profile_controller.dart, poem_screen.dart, poem_list_sheet.dart) پیدا
// شد: بررسی وضعیت، علامت‌گذاری، و شمارش کل.

abstract interface class IReadStatusStorage {
  /// آیا این شعر قبلاً خوانده شده است؟
  bool isRead(String id);

  /// این شعر را به‌عنوان خوانده‌شده علامت می‌زند. پیاده‌سازی باید از
  /// نوشتن تکراری جلوگیری کند اگر از قبل خوانده‌شده بوده (همان‌طور که
  /// منطق فعلی در poem_screen.dart هم همین‌کار را می‌کند).
  Future<void> markAsRead(String id);

  /// تعداد کل شعرهای خوانده‌شده.
  int get count;

  /// هر بار که یک شعر جدید علامت‌گذاری شود، یک رویداد منتشر می‌کند.
  /// این جایگزین Hive's `.listenable()` است.
  ///
  /// نکته: در کد فعلی، profile_controller.dart این stream را هیچ‌وقت
  /// واقعاً گوش نمی‌داد (یک باگ ثبت‌شده در لاگ تصمیمات)؛ با پیاده‌سازی
  /// این متد، آن باگ به‌طور طبیعی برطرف می‌شود.
  Stream<void> watch();
}
