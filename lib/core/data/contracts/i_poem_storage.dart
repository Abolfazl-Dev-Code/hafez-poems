// قرارداد ذخیره‌سازی برای شعرهای کش‌شده (غزل، قصیده، رباعی، قطعه، منتسب،
// مثنوی/ساقی‌نامه).
//
// این فایل عمداً هیچ اشاره‌ای به Hive یا هر دیتابیس دیگری ندارد. هر کلاسی
// که این اینترفیس را پیاده‌سازی کند (مثلاً HivePoemStorage یا در آینده
// DriftPoemStorage) باید دقیقاً همین ۵ عملیات را پشتیبانی کند — نه بیشتر،
// نه کمتر؛ این ۵ عملیات همان چیزی است که BasePoemCacheService واقعاً از
// لایه‌ی ذخیره‌سازی نیاز دارد (منطق جست‌وجو و امتیازدهی جزو این قرارداد
// نیست، چون به دیتابیس ربطی ندارد — آن بخش در poem_search_logic.dart است).

abstract interface class IPoemStorage<T> {
  /// باکس/جدول مربوطه را باز/آماده می‌کند. باید قبل از هر عملیات دیگر
  /// یک‌بار صدا زده شود.
  Future<void> open();

  // همه‌ی آیتم‌های موجود را به‌صورت Map<id, item> برمی‌گرداند.
  /// برای پر کردن اولیه‌ی کش (init) استفاده می‌شود.
  Map<String, T> readAll();

  /// یک آیتم را با کلید مشخص ذخیره/به‌روزرسانی می‌کند.
  Future<void> put(String id, T item);

  /// چند آیتم را یک‌جا ذخیره می‌کند (برای preload که ممکن است صدها آیتم
  /// را همزمان بنویسد؛ نوشتن یک‌جا معمولاً از نوشتن تک‌تک سریع‌تر است).
  Future<void> putAll(Map<String, T> items);

  /// فشرده‌سازی فایل ذخیره‌سازی روی دیسک (housekeeping). اگر پیاده‌سازی
  /// جدید این مفهوم را نداشت (مثلاً دیتابیس‌های SQL نیازی به compact
  /// دستی ندارند)، پیاده‌سازی می‌تواند این متد را no-op بگذارد.
  Future<void> compact();
}
